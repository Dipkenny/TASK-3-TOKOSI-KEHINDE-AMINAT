CREATE TABLE retailsales (
OrderID VARCHAR PRIMARY KEY,
Date DATE,
CustomerID VARCHAR,
Product VARCHAR,
Quantity INT,
UnitPrice DECIMAL,
ShippingAddress VARCHAR,
PaymentMethod VARCHAR,
OrderStatus VARCHAR,
TrackingNumber VARCHAR,
ItemsInCart INT,
CouponCode VARCHAR,
ReferralSource VARCHAR,
TotalPrice DECIMAL
);
SELECT * FROM retailsales

SELECT COUNT(*) FROM retailsales;

SELECT * FROM retailsales
LIMIT 10;

SELECT column_name, data_type FROM information_schema.columns 
WHERE table_name ='retailsales';

-- PRODUCT SALES RECORDS--
SELECT orderid, product, unitprice, quantity, totalprice FROM retailsales;

-- HIGH-VALUE ORDER--
SELECT orderid, product, quantity, totalprice FROM retailsales
WHERE totalprice >= 2000
ORDER BY totalprice DESC;

-- LOW-VALUE ORDER--
SELECT orderid, product, quantity, totalprice FROM retailsales
WHERE totalprice < 2000
ORDER BY totalprice ASC;

-- PRODUCT QUANTITY RANKING--
SELECT product, SUM(quantity) AS totalquantity FROM retailsales
GROUP BY product
ORDER BY SUM(quantity) DESC;

-- TOTAL REVENUE GENERATED BY EACH PRODCUCT--
SELECT product, SUM(totalprice) AS totalrevenue FROM retailsales
GROUP BY product
ORDER BY totalrevenue DESC;

-- PAYMENT METHOD DISTRIBUTION--
SELECT paymentmethod, COUNT(orderid) AS totalorder FROM retailsales
GROUP BY paymentmethod;

-- REFERRAL SOURCE PERFORMANCE--
SELECT referralsource, COUNT(orderid) as totalorder FROM retailsales
GROUP BY referralsource
ORDER BY totalorder DESC;

-- TOP 10 ORDERS--
SELECT orderid, product, quantity, totalprice FROM retailsales
ORDER BY totalprice DESC
LIMIT 10;

-- AVERAGE ORDER VALUE BY PRODUCT--
SELECT product, AVG(totalprice) AS Avgtotalprice FROM retailsales
GROUP BY product
ORDER BY Avgtotalprice DESC;
